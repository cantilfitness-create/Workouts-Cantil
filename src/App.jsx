// Semana do ano (padrão ISO: começa na segunda). Renova sozinho a cada ano.
function semanaDoAno(entrada) {
  const data = entrada ? new Date(entrada) : new Date();
  const d = new Date(Date.UTC(data.getFullYear(), data.getMonth(), data.getDate()));
  const dia = d.getUTCDay() || 7;
  d.setUTCDate(d.getUTCDate() + 4 - dia);
  const ano = d.getUTCFullYear();
  const inicio = new Date(Date.UTC(ano, 0, 1));
  const semana = Math.ceil(((d - inicio) / 86400000 + 1) / 7);
  const ult = new Date(Date.UTC(ano, 11, 28));
  const diaUlt = ult.getUTCDay() || 7;
  ult.setUTCDate(ult.getUTCDate() + 4 - diaUlt);
  const total = Math.ceil(((ult - inicio) / 86400000 + 1) / 7);
  return { semana, total, ano };
}

