function ApresentacoesMetodo({ apresentacoes, setApresentacoes, senha, onToast }) {
  const { pedir, Modal } = useSenhaGate(senha);
  const [sheetAberto, setSheetAberto] = useState(false);
  const [editandoId, setEditandoId] = useState(null);
  const [salvando, setSalvando] = useState(false);
  const [processandoImagem, setProcessandoImagem] = useState(false);
  const [erro, setErro] = useState("");
  const [form, setForm] = useState({ tag: "SOBRE O MÉTODO", titulo: "", descricao: "", imagemUrl: "" });

  const escolherFoto = async (e) => {
    const arquivo = e.target.files && e.target.files[0];
    e.target.value = "";
    if (!arquivo) return;
    setProcessandoImagem(true);
    try {
      const dataUrl = await comprimirImagem(arquivo, 800, 0.65);
      setForm((f) => ({ ...f, imagemUrl: dataUrl }));
    } catch (err) {
      console.error(err);
    }
    setProcessandoImagem(false);
  };

  const abrirNovo = () => pedir(() => {
    setEditandoId(null);
    setForm({ tag: "SOBRE O MÉTODO", titulo: "", descricao: "", imagemUrl: "" });
    setErro("");
    setSheetAberto(true);
  });
  const abrirEdicao = (ap) => pedir(() => {
    setEditandoId(ap.id);
    setForm(ap);
    setErro("");
    setSheetAberto(true);
  });
  // Exclusão só existe dentro da tela de edição (que já exige a senha)
  const excluirDaEdicao = () => pedir(async () => {
    if (!editandoId || !window.confirm("Excluir esta apresentação? Essa ação não pode ser desfeita.")) return;
    await excluirApresentacaoDb(editandoId);
    setApresentacoes((prev) => prev.filter((a) => a.id !== editandoId));
    setSheetAberto(false);
    if (onToast) onToast("Apresentação excluída");
  });

  const mover = (id, direcao) => pedir(async () => {
    const idx = apresentacoes.findIndex((a) => a.id === id);
    const novoIdx = idx + direcao;
    if (novoIdx < 0 || novoIdx >= apresentacoes.length) return;
    const atual = apresentacoes[idx];
    const vizinho = apresentacoes[novoIdx];
    const novos = [...apresentacoes];
    novos[idx] = { ...vizinho, ordem: atual.ordem };
    novos[novoIdx] = { ...atual, ordem: vizinho.ordem };
    novos.sort((a, b) => a.ordem - b.ordem);
    setApresentacoes(novos);
    await Promise.all([
      atualizarOrdemApresentacaoDb(atual.id, vizinho.ordem),
      atualizarOrdemApresentacaoDb(vizinho.id, atual.ordem),
    ]);
  });

  const salvar = async () => {
    setSalvando(true);
    setErro("");
    if (editandoId) {
      const ok = await atualizarApresentacaoDb(editandoId, form);
      setSalvando(false);
      if (!ok) { setErro("Não consegui salvar no banco. Confirme se a tabela \"apresentacoes\" existe no Supabase."); return; }
      setApresentacoes((prev) => prev.map((a) => (a.id === editandoId ? { ...a, ...form, id: editandoId, atualizadoEm: new Date().toISOString() } : a)));
    } else {
      const proximaOrdem = apresentacoes.length > 0 ? Math.max(...apresentacoes.map((a) => a.ordem || 0)) + 1 : 0;
      const nova = await inserirApresentacaoDb(form, proximaOrdem);
      setSalvando(false);
      if (!nova) { setErro("Não consegui salvar no banco. Confirme se a tabela \"apresentacoes\" existe no Supabase (rode o supabase-schema.sql)."); return; }
      setApresentacoes((prev) => [...prev, nova]);
    }
    setSheetAberto(false);
    if (onToast) onToast("Apresentação salva!");
  };

  return (
    <div>
      {apresentacoes.map((ap, i) => (
        <BlocoApresentacao
          key={ap.id}
          ap={ap}
          onEditar={abrirEdicao}
          onMoverCima={(id) => mover(id, -1)}
          onMoverBaixo={(id) => mover(id, 1)}
          ehPrimeiro={i === 0}
          ehUltimo={i === apresentacoes.length - 1}
        />
      ))}

      <button
        onClick={abrirNovo}
        style={{
          width: "100%", background: "none", border: "1px dashed #3A3B40", borderRadius: 10, padding: "14px",
          color: "#71727A", fontSize: 12.5, cursor: "pointer", display: "flex", alignItems: "center",
          justifyContent: "center", gap: 6, marginBottom: 22,
        }}
      >
        <Plus size={14} /> Adicionar apresentação do método
      </button>

      {Modal}

      {sheetAberto && (
        <Sheet title={editandoId ? "Editar apresentação" : "Nova apresentação"} onClose={() => setSheetAberto(false)}>
          <Field label="Etiqueta pequena (opcional)">
            <TextInput value={form.tag || ""} onChange={(e) => setForm({ ...form, tag: e.target.value })} placeholder="Ex: SOBRE O MÉTODO" />
          </Field>
          <Field label="Título grande">
            <AutoTextArea
              value={form.titulo}
              onChange={(e) => setForm({ ...form, titulo: e.target.value })}
              placeholder='Ex: "CANTIL É UM MÉTODO DE TREINO FUNCIONAL"'
              style={{ minHeight: 70 }}
            />
          </Field>
          <Field label="Texto de apresentação">
            <AutoTextArea
              value={form.descricao}
              onChange={(e) => setForm({ ...form, descricao: e.target.value })}
              placeholder="Explique sua proposta, filosofia de treino, o que torna o método diferente..."
              style={{ minHeight: 140 }}
            />
          </Field>
          <Field label="Foto (opcional, compactada automaticamente)">
            <input
              type="file"
              accept="image/*"
              onChange={escolherFoto}
              style={{ color: "#B9BABF", fontSize: 13, width: "100%" }}
            />
            {processandoImagem && (
              <div style={{ fontSize: 11.5, color: "#71727A", marginTop: 6 }}>Compactando imagem...</div>
            )}
            {form.imagemUrl && !processandoImagem && (
              <div style={{ display: "flex", alignItems: "center", gap: 10, marginTop: 8 }}>
                <img
                  src={form.imagemUrl}
                  alt=""
                  style={{ width: 56, height: 56, borderRadius: 8, objectFit: "cover", border: "1px solid #3A3B40" }}
                />
                <GhostButton onClick={() => setForm({ ...form, imagemUrl: "" })}>Remover foto</GhostButton>
              </div>
            )}
          </Field>
          {erro && <div style={{ color: "#E6483F", fontSize: 12.5, marginBottom: 12 }}>{erro}</div>}
          <PrimaryButton onClick={salvar} disabled={salvando || processandoImagem} style={{ width: "100%" }}>
            <Save size={16} /> {salvando ? "Salvando..." : processandoImagem ? "Aguarde a imagem..." : "Salvar apresentação"}
          </PrimaryButton>
          {editandoId && (
            <GhostButton onClick={excluirDaEdicao} style={{ width: "100%", marginTop: 10, color: "#E6483F", borderColor: "#E6483F55" }}>
              <Trash2 size={15} /> Excluir apresentação
            </GhostButton>
          )}
        </Sheet>
      )}
    </div>
  );
}

